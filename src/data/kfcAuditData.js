export const SCORING_MATRIX_RULES = [
  'The higher the number, the more severe, for each audit point.',
  '1 x L3 = Fail & potential loss of license if found to sell non-halal chicken. In case of fail with no loss of license then 2 follow up audits.',
  '2 x L2 = Fail & 2 follow up audits.',
  '2 x L1 & 1 x L2 = Fail & 1 follow up audit.',
  '3 x L1 = Fail & 1 follow up audit.'
];

export function evaluateChecklistOutcome(scoresObj = {}) {
  const vals = Object.values(scoresObj);
  const l3Count = vals.filter((v) => v === 'L3').length;
  const l2Count = vals.filter((v) => v === 'L2').length;
  const l1Count = vals.filter((v) => v === 'L1').length;

  if (l3Count >= 1) {
    return {
      category: 'L3_FAIL',
      label: 'L3 Fail',
      followUp: 'Potential loss of license / 2 follow-up audits',
      l1Count,
      l2Count,
      l3Count
    };
  }
  if (l2Count >= 2) {
    return {
      category: 'OTHER_FAIL',
      label: 'L2 Fail (2x L2)',
      followUp: 'Fail & 2 follow-up audits',
      l1Count,
      l2Count,
      l3Count
    };
  }
  if (l1Count >= 2 && l2Count >= 1) {
    return {
      category: 'OTHER_FAIL',
      label: 'L1/L2 Fail (2x L1 + 1x L2)',
      followUp: 'Fail & 1 follow-up audit',
      l1Count,
      l2Count,
      l3Count
    };
  }
  if (l1Count >= 3) {
    return {
      category: 'OTHER_FAIL',
      label: 'L1 Fail (3x L1)',
      followUp: 'Fail & 1 follow-up audit',
      l1Count,
      l2Count,
      l3Count
    };
  }
  return {
    category: 'PASSED',
    label: 'Recommend For Pass',
    followUp: 'Subject to HFA Admin / Certification Committee approval',
    l1Count,
    l2Count,
    l3Count
  };
}
